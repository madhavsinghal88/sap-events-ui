const EVENT_TYPE_KEYS = {
  'In-person': 'typeInPerson',
  'Virtual - Live': 'typeVirtualLive',
  'Virtual - On-demand': 'typeVirtualOnDemand',
  Hybrid: 'typeHybrid',
  Online: 'typeOnline',
};

export function t(lang, key) {
  const dict = UI[lang] || UI.en;
  return dict[key] || UI.en[key] || key;
}

export function translateEventType(lang, type) {
  const key = EVENT_TYPE_KEYS[type];
  if (!key) return type || '';
  return t(lang, key);
}

